#include "propup_ltv_mpc/LTV_MPC.hpp"
#include "propup_ltv_mpc/PredictionModel.hpp"
#include "propup_ltv_mpc/MPCCost.hpp"

#include <Eigen/Dense>
#include <array>
#include <iostream>

int main()
{
    const int N = 10;
    const double dt = 0.02;
    const double mass = 12.0;

    LTV_MPC dynamics;

    Eigen::Matrix3d inertia = Eigen::Matrix3d::Zero();
    inertia.diagonal() << 0.1, 0.25, 0.3;

    dynamics.setRobotParameters(mass, inertia);

    LTV_MPC::StateVector x0 =
        LTV_MPC::StateVector::Zero();

    x0(5) = 0.30;
    x0(12) = -9.81;

    std::array<Eigen::Vector3d, 4> feet = {
        Eigen::Vector3d( 0.20,  0.10, -0.30),
        Eigen::Vector3d( 0.20, -0.10, -0.30),
        Eigen::Vector3d(-0.20,  0.10, -0.30),
        Eigen::Vector3d(-0.20, -0.10, -0.30)
    };

    dynamics.computeContinuousDynamics(x0, feet);
    dynamics.discretizeDynamics(dt);

    PredictionModel prediction(N);

    prediction.computePredictionMatrices(
        dynamics.getAd(),
        dynamics.getBd()
    );

    Eigen::MatrixXd P = prediction.getP();
    Eigen::MatrixXd H = prediction.getH();

    // Nominal forces for all prediction steps
    Eigen::VectorXd U_ref = Eigen::VectorXd::Zero(12 * N);

    for (int k = 0; k < N; ++k)
    {
        for (int leg = 0; leg < 4; ++leg)
        {
            U_ref(k * 12 + leg * 3 + 2) =
                mass * 9.81 / 4.0;
        }
    }

    // Reference trajectory generated by nominal forces
    Eigen::VectorXd X_ref = P * x0 + H * U_ref;

    // MPC weights
    Eigen::MatrixXd Q =
        Eigen::MatrixXd::Identity(13 * N, 13 * N);

    Eigen::MatrixXd R =
        0.001 * Eigen::MatrixXd::Identity(12 * N, 12 * N);

    MPCCost cost;
    cost.setWeights(Q, R);

    cost.computeCost(P, H, x0, X_ref, U_ref);

    Eigen::MatrixXd G = cost.getHessian();
    Eigen::VectorXd g = cost.getGradient();

    // Check first-order optimality at U_ref
    Eigen::VectorXd residual = G * U_ref + g;

    std::cout << "Hessian dimensions: "
              << G.rows() << " x " << G.cols() << "\n";

    std::cout << "Gradient dimensions: "
              << g.size() << "\n";

    std::cout << "Optimality residual: "
              << residual.norm() << "\n";

    if (residual.norm() < 1e-7)
    {
        std::cout << "\nNOMINAL COST TEST PASSED!\n";
        return 0;
    }

    std::cout << "\nNOMINAL COST TEST FAILED!\n";
    return 1;
}
